"""
Utility classes shared by the on-policy actor-critic implementations
(PPO and TRPO) in this project.

Contents
--------
- RunningNormalizer : running mean/std normalizer used to standardize
  observations, which stabilizes on-policy training on Pendulum.
- RolloutBuffer     : stores the transitions collected under the CURRENT
  policy for one update and computes Generalized Advantage Estimation
  (GAE) targets.
"""
import os
import platform
import shutil
import subprocess
import sys
import venv

import numpy as np
import torch


class RunningNormalizer:
    """Welford running mean/variance for observation normalization."""

    def __init__(self, shape, epsilon=1e-4):
        self.mean = np.zeros(shape, dtype=np.float64)
        self.var = np.ones(shape, dtype=np.float64)
        self.count = epsilon

    def update(self, x):
        x = np.asarray(x, dtype=np.float64)
        batch_mean = x.mean(axis=0)
        batch_var = x.var(axis=0)
        batch_count = x.shape[0]

        delta = batch_mean - self.mean
        total = self.count + batch_count
        self.mean += delta * batch_count / total
        m_a = self.var * self.count
        m_b = batch_var * batch_count
        m2 = m_a + m_b + delta ** 2 * self.count * batch_count / total
        self.var = m2 / total
        self.count = total

    def normalize(self, x):
        return (np.asarray(x, dtype=np.float64) - self.mean) / np.sqrt(self.var + 1e-8)


class RolloutBuffer:
    """Fixed-size on-policy buffer with GAE-lambda advantage estimation.

    All transitions belong to the trajectory generated by the current
    policy. After a full batch is collected the buffer computes the
    advantages and the value targets in ``compute_returns_and_advantages``.
    """

    def __init__(self, size, state_size, action_size, gamma, gae_lambda, device):
        self.states = np.zeros((size, state_size), dtype=np.float32)
        self.actions = np.zeros((size, action_size), dtype=np.float32)
        self.rewards = np.zeros(size, dtype=np.float32)
        self.values = np.zeros(size, dtype=np.float32)
        self.log_probs = np.zeros(size, dtype=np.float32)
        self.dones = np.zeros(size, dtype=np.float32)

        self.advantages = np.zeros(size, dtype=np.float32)
        self.returns = np.zeros(size, dtype=np.float32)

        self.gamma = gamma
        self.gae_lambda = gae_lambda
        self.device = device
        self.max_size = size
        self.ptr = 0

    def add(self, state, action, reward, value, log_prob, done):
        idx = self.ptr
        self.states[idx] = state
        self.actions[idx] = action
        self.rewards[idx] = reward
        self.values[idx] = value
        self.log_probs[idx] = log_prob
        self.dones[idx] = done
        self.ptr += 1

    def is_full(self):
        return self.ptr >= self.max_size

    def compute_returns_and_advantages(self, last_value):
        """Generalized Advantage Estimation (GAE-lambda).

        last_value : the critic estimate V(s_T) that bootstraps the
                     final (possibly truncated) step.
        """
        last_gae = 0.0
        for t in reversed(range(self.ptr)):
            if t == self.ptr - 1:
                next_value = last_value
            else:
                next_value = self.values[t + 1]
            next_non_terminal = 1.0 - self.dones[t]
            delta = self.rewards[t] + self.gamma * next_value * next_non_terminal - self.values[t]
            last_gae = delta + self.gamma * self.gae_lambda * next_non_terminal * last_gae
            self.advantages[t] = last_gae
        self.returns[:self.ptr] = self.advantages[:self.ptr] + self.values[:self.ptr]

    def get(self):
        """Return the whole batch as torch tensors and reset the pointer."""
        n = self.ptr
        adv = self.advantages[:n]
        adv = (adv - adv.mean()) / (adv.std() + 1e-8)

        batch = (
            torch.as_tensor(self.states[:n], device=self.device),
            torch.as_tensor(self.actions[:n], device=self.device),
            torch.as_tensor(self.log_probs[:n], device=self.device),
            torch.as_tensor(adv, device=self.device),
            torch.as_tensor(self.returns[:n], device=self.device),
            torch.as_tensor(self.values[:n], device=self.device),
        )
        self.ptr = 0
        return batch

    def __len__(self):
        return self.ptr


class OUNoise:
    """Simple Ornstein-Uhlenbeck process for temporally correlated noise."""

    def __init__(self, size, mu=0.0, theta=0.15, sigma=0.2):
        self.size = size
        self.mu = mu * np.ones(size, dtype=np.float32)
        self.theta = theta
        self.sigma = sigma
        self.state = self.mu.copy()

    def reset(self):
        self.state = self.mu.copy()

    def sample(self):
        dx = self.theta * (self.mu - self.state) + self.sigma * np.random.randn(self.size)
        self.state = self.state + dx
        return self.state


class OUActionNoise:
    """Ornstein-Uhlenbeck action noise compatible with the DDPG/SAC code."""

    def __init__(self, mean, std_deviation, theta=0.15, dt=1e-2, x_initial=None):
        self.theta = theta
        self.mean = np.asarray(mean, dtype=np.float32)
        self.std_dev = np.asarray(std_deviation, dtype=np.float32)
        self.dt = dt
        self.x_initial = None if x_initial is None else np.asarray(x_initial, dtype=np.float32)
        self.reset()

    def __call__(self):
        noise = np.random.normal(size=self.mean.shape).astype(np.float32)
        x = (
            self.x_prev
            + self.theta * (self.mean - self.x_prev) * self.dt
            + self.std_dev * np.sqrt(self.dt) * noise
        )
        self.x_prev = x
        return x

    def reset(self):
        if self.x_initial is None:
            self.x_prev = np.zeros_like(self.mean)
        else:
            self.x_prev = self.x_initial.copy()


def _venv_python_path(venv_dir):
    if platform.system() == "Windows":
        return os.path.join(venv_dir, "Scripts", "python.exe")
    return os.path.join(venv_dir, "bin", "python")


def _python_version(python_executable):
    result = subprocess.run(
        [python_executable, "-c", "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')"],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip()


def _select_python_executable():
    candidates = [sys.executable]
    for name in ("python3.12", "python3.11", "python3.10"):
        python_path = shutil.which(name)
        if python_path and python_path not in candidates:
            candidates.append(python_path)

    for candidate in candidates:
        version = _python_version(candidate)
        if version in {"3.10", "3.11", "3.12"}:
            return candidate, version

    current = _python_version(sys.executable)
    raise RuntimeError(
        "Could not find a supported Python interpreter for this project. "
        f"Found current interpreter version {current}; expected one of 3.10, 3.11, or 3.12."
    )


def install_requirements():
    """Install every library required by this project.

    Reads ``requirements.txt`` located next to this file and installs the
    listed packages into a local ``.venv`` virtual environment. Run with
    ``python utilities.py``.
    """
    here = os.path.dirname(os.path.abspath(__file__))
    requirements_path = os.path.join(here, "requirements.txt")
    venv_dir = os.path.join(here, ".venv")

    if not os.path.exists(requirements_path):
        raise FileNotFoundError(f"Could not find requirements file: {requirements_path}")

    selected_python, selected_version = _select_python_executable()
    venv_python = _venv_python_path(venv_dir)

    recreate_venv = not os.path.exists(venv_python)
    if not recreate_venv:
        try:
            recreate_venv = _python_version(venv_python) != selected_version
        except Exception:
            recreate_venv = True

    if recreate_venv:
        print(f"Creating project virtual environment at {venv_dir} with Python {selected_version} ...")
        subprocess.check_call([selected_python, "-m", "venv", venv_dir, "--clear"])

    print(f"Installing project requirements from {requirements_path} into {venv_dir} ...")
    subprocess.check_call([venv_python, "-m", "pip", "install", "--upgrade", "pip"])
    subprocess.check_call(
        [venv_python, "-m", "pip", "install", "-r", requirements_path]
    )
    print("All required libraries are installed.")
    print(f"Use {venv_python} to run the project scripts.")


if __name__ == "__main__":
    install_requirements()

